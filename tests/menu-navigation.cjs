const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const base=process.env.WEERLAB_TEST_URL || 'http://127.0.0.1:8791';
(async()=>{
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>{if(/(?:menu|product-host)\.js/.test(e.stack||''))errors.push(e.message);});
// The regression test verifies navigation with remote weather APIs and CDNs blocked.
await page.route('**/*',route=>{const u=new URL(route.request().url());return u.origin===new URL(base).origin?route.continue():route.abort();});
await page.goto(`${base}/index.html`);
await page.getByRole('heading',{name:'Jouw weeroverzicht'}).waitFor();
await page.locator('#desktop-nav a[data-route="verwachting"]').click();
await page.getByRole('heading',{name:'Wat gaat het weer doen?'}).waitFor();
assert(page.url().includes('#menu/verwachting'));
await page.locator('.subnav a').filter({hasText:'Pluimen'}).click();
await page.locator('a[href="index.html#pluim"]').first().click();
await page.locator('#product-workspace:not([hidden])').waitFor();
const host=page.frameLocator('#product-frame');
await host.locator('#panel-pluim.actief').waitFor();
assert.equal(await host.locator('#productnavigatie').isVisible(),false);
assert.equal(await host.locator('.hoofd > .topbar').isVisible(),false);
assert.equal(await page.locator('#desktop-nav').isVisible(),true);
await host.getByRole('button',{name:'Ensemble 6 pluim',exact:true}).click();
await page.waitForFunction(()=>location.hash==='#pluim-ens6');
await page.goBack({waitUntil:'commit'});await page.waitForFunction(()=>location.hash==='#pluim');
await host.locator('#panel-pluim.actief').waitFor();
await page.locator('#desktop-nav a[data-route="start"]').click();await page.getByRole('heading',{name:'Jouw weeroverzicht'}).waitFor();
await page.locator('#search').fill('radar');
await page.locator('.row-link').first().waitFor();
await page.locator('a[href="index.html#radar"]').first().click();
await host.locator('#panel-radar.actief').waitFor();
await page.goto(`${base}/index.html#neerslag668`);
await host.locator('#panel-neerslag668.actief').waitFor();
assert.equal(await host.locator('#productnavigatie').isVisible(),false);
await page.goto(`${base}/index.html#home`);await page.getByRole('heading',{name:'Jouw weeroverzicht'}).waitFor();
await page.goto(`${base}/demo_menu_v9.html#verwachting`);
await page.waitForURL('**/index.html#menu/verwachting');
await page.getByRole('heading',{name:'Wat gaat het weer doen?'}).waitFor();
if(process.env.WEERLAB_SCREENSHOT_DIR)await page.screenshot({path:process.env.WEERLAB_SCREENSHOT_DIR+'/menu-desktop.png'});
await page.setViewportSize({width:390,height:844});
await page.locator('#mobile-nav a').filter({hasText:'Overzicht'}).click();
await page.getByRole('heading',{name:'Jouw weeroverzicht'}).waitFor();
await page.locator('a[href="index.html#pluim"]').first().click();
await host.locator('#panel-pluim.actief').waitFor();
assert.equal(await host.locator('#productnavigatie').isVisible(),false);
assert.equal(await host.locator('#hoofdinhoud').getAttribute('inert'),null);
await page.locator('#open-menu').click();await page.locator('#menu-dialog[open]').waitFor();
await page.locator('#close-menu').click();
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
if(process.env.WEERLAB_SCREENSHOT_DIR)await page.screenshot({path:process.env.WEERLAB_SCREENSHOT_DIR+'/menu-mobile.png'});
assert.deepEqual(errors,[], 'No errors in the shared navigation or route bridge');
console.log(JSON.stringify({checks:'home, category, pluim, subtabs, back, search, radar, deeplink, demo redirect, mobile dialog and overflow',errors},null,2));
await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
